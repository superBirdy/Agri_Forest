def results_to_df(results: PanelOLS):
    """Build a tidy dataframe with coef, se, t, p, and 95% CI."""
    params = results.params.rename("coef")
    se = results.std_errors.rename("std_err")
    tstats = results.tstats.rename("t")
    pvals = results.pvalues.rename("pval")
    ci = results.conf_int()
    ci.columns = ["ci_lo", "ci_hi"]
    out = pd.concat([params, se, tstats, pvals, ci], axis=1)
    out.index.name = "term"
    return out.reset_index()

def render_html_block(title, meta_badges: dict, df: pd.DataFrame, notes: list):
    """Return HTML for a single model block (title + meta + table + notes)."""
    cols = ["term", "coef", "std_err", "t", "pval", "ci_lo", "ci_hi"]
    show_cols = [c for c in cols if c in df.columns]
    df_fmt = df.copy()
    for c in ["coef", "std_err", "t", "ci_lo", "ci_hi"]:
        if c in df_fmt.columns:
            df_fmt[c] = df_fmt[c].map(lambda x: f"{x:,.4f}")
    if "pval" in df_fmt.columns:
        df_fmt["pval"] = df_fmt["pval"].map(lambda x: f"{x:.3g}")
    df_fmt["term"] = df_fmt["term"].astype(str)

    meta_html = " ".join([f'<span class="badge">{k}: {v}</span>' for k, v in meta_badges.items()])
    table_html = df_fmt[show_cols].to_html(index=False, escape=False, classes="reg-table")
    notes_html = "<br>".join([f'<span class="small">* {n}</span>' for n in notes])

    block = f"""
    <h2>{title}</h2>
    <div>{meta_html}</div>
    <div class="table-wrap">{table_html}</div>
    <div>{notes_html}</div>
    <hr>
    """
    return block

